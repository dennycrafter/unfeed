// Bundles src/inject/*.ts (which pull in src/rules/*.json through the shared
// matcher) into plain JS strings under src/inject/generated/, so the app and
// the userscripts (T6) are built from one source and never drift. Replaces
// the T0 stub, as planned in ASSUMPTIONS note 4.

import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(__dirname, '..');

const entries: Array<{ entry: string; exportName: string }> = [
  { entry: 'instagram', exportName: 'INSTAGRAM_INJECT_SCRIPT' },
  { entry: 'linkedin', exportName: 'LINKEDIN_INJECT_SCRIPT' },
];

async function main(): Promise<void> {
  const outDir = join(root, 'src', 'inject', 'generated');
  mkdirSync(outDir, { recursive: true });

  for (const { entry, exportName } of entries) {
    const result = await build({
      entryPoints: [join(root, 'src', 'inject', `${entry}.ts`)],
      bundle: true,
      write: false,
      format: 'iife',
      platform: 'browser',
      target: ['es2019'],
      minify: false,
      legalComments: 'none',
      logLevel: 'warning',
      // Hide CSS imports are inlined as strings (see src/inject/css.d.ts).
      loader: { '.css': 'text' },
    });
    const js = result.outputFiles[0].text;
    const module = `// Generated by scripts/build-inject.ts. Do not edit by hand; change
// src/inject and src/rules, then run npm run build:inject.

export const ${exportName} = ${JSON.stringify(js)};
`;
    writeFileSync(join(outDir, `${entry}.generated.ts`), module);
    console.log(`build:inject: wrote src/inject/generated/${entry}.generated.ts (${js.length} chars)`);
  }
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
