// Bundles src/inject/*.ts (which pull in src/rules/*.json through the shared
// matcher) into plain JS strings under src/inject/generated/, so the app and
// the userscripts (T6) are built from one source and never drift. Replaces
// the T0 stub, as planned in ASSUMPTIONS note 4.

import { build, type Plugin } from 'esbuild';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';
import { parseNamedCss } from '../src/inject/cssRules';

const root = resolve(__dirname, '..');

/** Inlines the named css files as string modules. Files with @unfeed-rule
 * markers are validated (a marker without css blocks fails the build, so a
 * broken rule can never ship); files without markers pass through unchanged
 * (the LinkedIn css predates named rules). */
const namedCssPlugin: Plugin = {
  name: 'unfeed-named-css',
  setup(buildPlugin) {
    buildPlugin.onLoad({ filter: /\.css$/ }, (args) => {
      const text = readFileSync(args.path, 'utf8');
      const rules = parseNamedCss(text);
      if (rules.length === 0) {
        console.log(`build:inject: ${basename(args.path)}: no named rules, passing through`);
        return { contents: `export default ${JSON.stringify(text)};`, loader: 'js' };
      }
      for (const rule of rules) {
        if (rule.blocks.length === 0) {
          return { errors: [{ text: `rule ${rule.id} in ${args.path} has no css blocks` }] };
        }
      }
      console.log(`build:inject: ${basename(args.path)}: ${rules.map((rule) => rule.id).join(', ')}`);
      return { contents: `export default ${JSON.stringify(text)};`, loader: 'js' };
    });
  },
};

const entries: Array<{ entry: string; exportName: string }> = [
  { entry: 'instagram', exportName: 'INSTAGRAM_INJECT_SCRIPT' },
  { entry: 'linkedin', exportName: 'LINKEDIN_INJECT_SCRIPT' },
];

async function main(): Promise<void> {
  const outDir = join(root, 'src', 'inject', 'generated');
  mkdirSync(outDir, { recursive: true });

  for (const { entry, exportName } of entries) {
    const result = await build({
      entryPoints: [join(root, 'src', 'inject', `${entry}.ts`)],
      bundle: true,
      write: false,
      format: 'iife',
      platform: 'browser',
      target: ['es2019'],
      minify: false,
      legalComments: 'none',
      logLevel: 'warning',
      // Hide css imports are inlined as strings and validated by the plugin.
      plugins: [namedCssPlugin],
    });
    const js = result.outputFiles[0].text;
    const module = `// Generated by scripts/build-inject.ts. Do not edit by hand; change
// src/inject and src/rules, then run npm run build:inject.

export const ${exportName} = ${JSON.stringify(js)};
`;
    writeFileSync(join(outDir, `${entry}.generated.ts`), module);
    console.log(`build:inject: wrote src/inject/generated/${entry}.generated.ts (${js.length} chars)`);
  }
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
