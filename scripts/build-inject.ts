// Bundles src/rules/*.json and src/inject/*.ts into plain JS strings under
// src/inject/generated/ and into the userscripts/ folder, so the app and the
// userscripts never drift.
//
// T0 scaffold: this stub only creates the generated folder and a placeholder
// module so CI can run build:inject. T1 replaces it with the real bundler
// (route rules + hide CSS + history hooks).

import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const outDir = join(process.cwd(), 'src', 'inject', 'generated');

mkdirSync(outDir, { recursive: true });

const placeholder = `// Generated by scripts/build-inject.ts. Do not edit by hand.
// The real bundling of route rules, hide CSS and history hooks lands in T1.

export const INJECT_BUNDLE_VERSION = 0;
`;

writeFileSync(join(outDir, 'bundle.ts'), placeholder);

console.log('build:inject: wrote src/inject/generated/bundle.ts (T0 placeholder)');
